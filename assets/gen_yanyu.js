  function buildPassage(rnd, n) {
    var out = [], i, q, k;
    for (i = 0; i < PASSAGES.length; i++) {
      var ps = PASSAGES[i];
      for (q = 0; q < 4; q++) {
        var opts = [ps.r], used = [], exp = '文段围绕“' + ps.r + '”展开。';
        for (k = 0; k < 4; k++) {
          if (k === q) continue;
          opts.push(ps.x[k][1]);
          used.push(ps.x[k]);
        }
        opts = shuffle(opts, rnd);
        for (k = 0; k < used.length; k++) {
          exp += '干扰项“' + used[k][1] + '”属于' + used[k][0] + '，' + used[k][2] + '。';
        }
        exp += '正确项准确概括了文段的主旨，其他各项均不能涵盖全文。';
        out.push({
          id: nid(), mod: '言语理解', tag: '片段阅读', level: 1 + ((i + q) % 3),
          stem: ps.p + PASSAGE_QS[q],
          opts: opts, ans: opts.indexOf(ps.r), exp: exp
        });
      }
    }
    return out;
  }

  

